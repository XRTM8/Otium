#!/usr/bin/env node
/**
 * Single-version guard.
 *
 * Otium ships a Windows installer, a portable Windows executable and an
 * Android APK from one tag. Every build tool reads its own version file, so a
 * half-finished bump can silently ship mismatched artifacts. This script makes
 * package.json the source of truth and fails when anything else disagrees.
 *
 * Usage:
 *   node scripts/check-version.mjs            # check the working tree
 *   node scripts/check-version.mjs v0.2.0     # also require this release tag
 *   node scripts/check-version.mjs --tag v0.2.0
 */
import { readFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const failures = [];
const checks = [];

function read(relativePath) {
  return readFileSync(path.join(root, relativePath), 'utf8');
}

function check(label, actual, expected) {
  checks.push({ label, actual, expected, ok: actual === expected });
  if (actual !== expected) {
    failures.push(`${label}: expected ${expected}, found ${actual}`);
  }
}

function parseJson(relativePath) {
  try {
    return JSON.parse(read(relativePath));
  } catch (error) {
    failures.push(`${relativePath}: ${error.message}`);
    return null;
  }
}

function cargoPackageVersion(toml) {
  const section = /^\[package\]\s*$([\s\S]*?)(?=^\[|(?![\s\S]))/m.exec(toml);
  if (!section) return null;
  const version = /^\s*version\s*=\s*"([^"]+)"/m.exec(section[1]);
  return version ? version[1] : null;
}

function cargoLockVersion(lock) {
  const blocks = lock.split(/^\[\[package\]\]\s*$/m);
  for (const block of blocks) {
    if (/^\s*name\s*=\s*"otium"\s*$/m.test(block)) {
      const version = /^\s*version\s*=\s*"([^"]+)"/m.exec(block);
      return version ? version[1] : null;
    }
  }
  return null;
}

function normalizeTag(value) {
  return value
    .trim()
    .replace(/^refs\/tags\//i, '')
    .replace(/^otium[-_]?/i, '')
    .replace(/^v/i, '');
}

const args = process.argv.slice(2);
const explicitTag =
  args.find((argument) => !argument.startsWith('--')) ??
  args.find((argument) => argument.startsWith('--tag='))?.slice('--tag='.length) ??
  '';
const tag = explicitTag || process.env.GITHUB_REF_NAME || '';

const packageJson = parseJson('package.json');
if (!packageJson) {
  report();
  process.exit(1);
}

const version = packageJson.version;
check('package.json version (source of truth)', version, version);
if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(version)) {
  failures.push(`package.json version "${version}" is not a valid semantic version`);
}

const tauriConfig = parseJson('src-tauri/tauri.conf.json');
if (tauriConfig) {
  check('src-tauri/tauri.conf.json version', tauriConfig.version, version);
}

const cargoToml = read('src-tauri/Cargo.toml');
check('src-tauri/Cargo.toml [package] version', cargoPackageVersion(cargoToml), version);

const cargoLock = read('src-tauri/Cargo.lock');
check('src-tauri/Cargo.lock otium version', cargoLockVersion(cargoLock), version);

const packageLock = parseJson('package-lock.json');
if (packageLock) {
  check('package-lock.json version', packageLock.version, version);
  check('package-lock.json packages[""].version', packageLock.packages?.['']?.version, version);
}

if (tag) {
  const tagVersion = normalizeTag(tag);
  if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(tagVersion)) {
    failures.push(`release tag "${tag}" does not contain a semantic version`);
  } else {
    check(`release tag ${tag}`, tagVersion, version);
  }
}

// Release notes travel to Windows, Android and the GitHub release from this
// one file. If its title names a version, that version must be current.
if (existsSync(path.join(root, 'release-notes.md'))) {
  const firstLine = read('release-notes.md').split(/\r?\n/, 1)[0] ?? '';
  const notesVersion = /\b(\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?)\b/.exec(firstLine)?.[1];
  if (notesVersion) check('release-notes.md title version', notesVersion, version);
}

// Generated by the Tauri CLI on every Android build. It is ignored by git, so
// only report it when a stale file is sitting in the working tree.
const androidPropertiesPath = 'src-tauri/gen/android/app/tauri.properties';
if (existsSync(path.join(root, androidPropertiesPath))) {
  const properties = read(androidPropertiesPath);
  const versionName = /^tauri\.android\.versionName=(.+)$/m.exec(properties)?.[1]?.trim();
  if (versionName && versionName !== version) {
    checks.push({
      label: `${androidPropertiesPath} versionName (generated)`,
      actual: versionName,
      expected: version,
      ok: false,
      warning: true
    });
    console.warn(
      `warning: ${androidPropertiesPath} still says ${versionName}. ` +
        'The next `tauri android build` regenerates it.'
    );
  }
}

report();

function report() {
  for (const item of checks) {
    const mark = item.ok ? 'ok  ' : item.warning ? 'warn' : 'FAIL';
    console.log(`${mark} ${item.label}: ${item.actual}`);
  }

  if (failures.length > 0) {
    console.error('\nVersion check failed:');
    for (const failure of failures) console.error(`  - ${failure}`);
    console.error(
      '\nUpdate package.json, src-tauri/tauri.conf.json, src-tauri/Cargo.toml, ' +
        'Cargo.lock and package-lock.json together, then tag v<version>.'
    );
    process.exitCode = 1;
    return;
  }

  console.log(`\nOtium ${version} is consistent across all build inputs.`);
}
